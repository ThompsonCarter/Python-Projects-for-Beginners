# if statement
age = 20
if age >= 18:
    print("You are an adult.")

# else statement
age = 16
if age >= 18:
    print("You are an adult.")
else:
    print("You are a minor.")

# elif statement
age = 25
if age < 18:
    print("You are a minor.")
elif age < 21:
    print("You are a young adult.")
else:
    print("You are an adult.")
