
# Windows installation commands
# Step 1: Download Python
# Step 2: Run the installer with the checkbox "Add Python to PATH"
# Step 3: Verify with `python --version`

# macOS installation commands
# Step 1: Install Homebrew
# Step 2: Run `brew install python3`
# Step 3: Verify with `python3 --version`

# Linux installation commands
# Step 1: Run `sudo apt update`
# Step 2: Run `sudo apt install python3`
# Step 3: Verify with `python3 --version`
