
# 3. Operators: Manipulating Data

# Arithmetic Operators
x = 10
y = 3

# Addition
print(x + y)  # Output: 13

# Subtraction
print(x - y)  # Output: 7

# Multiplication
print(x * y)  # Output: 30

# Division
print(x / y)  # Output: 3.3333...

# Floor Division
print(x // y)  # Output: 3

# Modulus
print(x % y)  # Output: 1

# Exponentiation
print(x ** y)  # Output: 1000

# Comparison Operators
print(x == y)  # Output: False
print(x != y)  # Output: True
print(x > y)   # Output: True
print(x < y)   # Output: False
print(x >= y)  # Output: True
print(x <= y)  # Output: False

# Logical Operators
print(x > 5 and y < 10)  # Output: True
print(x > 15 or y < 10)  # Output: True
print(not (x > 5))  # Output: False
    